// FeatureType is one row of Appendix D.
//
// Code is the value TIGER writes into PRETYP and SUFTYP; it is the only field
// a reader of those fields has to start from. Prefix and Suffix report which
// of the two the Census Bureau permits the type in, and both are false for no
// row in the published table — every type is allowed somewhere.
//
// Translation is set only on the Spanish rows, and it is prose rather than a
// pointer: the Census Bureau's own English rendering of the word. Most of them
// name another row here (ACUEDUCTO translates AQUEDUCT, which is code 118),
// but some do not — AUTOPISTA translates "EXPRESSWAY OR FREEWAY" — so a
// consumer must not look a Translation up in this table and expect to find it.
type FeatureType struct {
	Code        string
	Full        string
	Short       string
	Spanish     bool
	Translation string
	Prefix      bool
	Suffix      bool
}

