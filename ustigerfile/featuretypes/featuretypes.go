// Package featuretypes holds Appendix D of the Census Bureau's TIGER/Line
// technical documentation as data.
//
// A TIGER FEATNAMES record does not carry a street name as a string. It
// carries a base name and four codes around it — PREQUAL, PRETYP, SUFTYP,
// SUFQUAL — and the name a reader recognizes only exists once those codes are
// expanded. This table is the SUFTYP and PRETYP half: the 503 feature types
// the Census Bureau names, with the abbreviation it displays for each.
//
// It is not Publication 28 Appendix C1 and must not be substituted for it.
// The two overlap on the ordinary street suffixes and disagree on the
// abbreviation for several of them, and this one carries hundreds of rows
// Publication 28 has no equivalent for — ACUEDUCTO, AIR FORCE BASE, ZOO. A
// consumer producing Project US@ output reads the Census abbreviation here and
// then resolves the word through streetsuffixes; reading only one of the two
// is what produces a key that misses.
//
// Rows are uppercase, following the rest of this module. The published table
// prints them in title case.
//
// Transcribed from
// https://www2.census.gov/geo/pdfs/maps-data/data/tiger/tgrshp2025/TGRSHP2025_TechDoc_D.pdf
// (TIGER/Line Shapefiles, 2025, Appendix D: Feature Name Types).
package featuretypes

